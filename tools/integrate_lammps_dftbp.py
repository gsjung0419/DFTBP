#!/usr/bin/env python3

from __future__ import annotations

import argparse
import shlex
import shutil
import subprocess
import sys
from pathlib import Path


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")


def replace_once(path: Path, old: str, new: str) -> bool:
    text = read_text(path)
    if new in text:
        return False
    if old not in text:
        raise RuntimeError(f"Could not find expected text in {path}")
    write_text(path, text.replace(old, new, 1))
    return True


def copy_tree(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(src, dst, dirs_exist_ok=True)


def copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)


def parse_pkgconfig(pc_path: Path) -> list[str]:
    libs = []
    for line in read_text(pc_path).splitlines():
      if line.startswith("Libs:"):
        libs.extend(shlex.split(line.split(":", 1)[1].strip()))
      elif line.startswith("Libs.private:"):
        libs.extend(shlex.split(line.split(":", 1)[1].strip()))
    return libs


def configure_makefile_linking(lib_dir: Path, dftbplus_prefix: Path | None) -> None:
    link_items: list[str] = []
    sysinc = ""

    if dftbplus_prefix is not None:
        pc_path = dftbplus_prefix / "lib" / "pkgconfig" / "dftbplus.pc"
        if pc_path.exists():
            link_items = parse_pkgconfig(pc_path)
        else:
            link_items = [f"-L{dftbplus_prefix / 'lib'}", "-ldftbplus"]
        sysinc = f"-I{dftbplus_prefix / 'include'}"

    content = (
        "# Auto-generated by integrate_lammps_dftbp.py\n"
        "# Edit these variables only if you need to override the detected\n"
        "# DFTB+ installation details.\n\n"
        f"dftbp_SYSINC = {sysinc}\n"
        f"dftbp_SYSLIB = {' '.join(link_items)}\n"
        "dftbp_SYSPATH =\n"
    )

    for name in ("Makefile.lammps", "Makefile.lammps.mpi"):
        write_text(lib_dir / name, content)


def stage_into_lammps(lammps_dir: Path, dftbplus_prefix: Path | None) -> None:
    root = repo_root()

    copy_tree(root / "src", lammps_dir / "src" / "DFTBP")
    copy_tree(root / "lib" / "dftbp", lammps_dir / "lib" / "dftbp")
    copy_file(root / "cmake" / "Modules" / "Packages" / "DFTBP.cmake",
              lammps_dir / "cmake" / "Modules" / "Packages" / "DFTBP.cmake")

    configure_makefile_linking(lammps_dir / "lib" / "dftbp", dftbplus_prefix)

    replace_once(
        lammps_dir / "src" / "Makefile",
        "\tdipole \\\n\tdpd-basic \\\n",
        "\tdipole \\\n\tdftbp \\\n\tdpd-basic \\\n",
    )

    replace_once(
        lammps_dir / "cmake" / "CMakeLists.txt",
        "  DIPOLE\n  DPD-BASIC\n",
        "  DIPOLE\n  DFTBP\n  DPD-BASIC\n",
    )

    replace_once(
        lammps_dir / "cmake" / "CMakeLists.txt",
        "        PLUMED QMMM ML-QUIP SCAFACOS MACHDYN VTK KIM COMPRESS ML-PACE LEPTON EXTRA-COMMAND)\n",
        "        PLUMED QMMM DFTBP ML-QUIP SCAFACOS MACHDYN VTK KIM COMPRESS ML-PACE LEPTON EXTRA-COMMAND)\n",
    )


def run(cmd: list[str], cwd: Path) -> None:
    print(f"+ (cd {cwd} && {' '.join(shlex.quote(x) for x in cmd)})")
    subprocess.run(cmd, cwd=cwd, check=True)


def build_make(lammps_dir: Path, jobs: int, target: str) -> None:
    src_dir = lammps_dir / "src"
    run(["make", "yes-dftbp"], src_dir)
    run(["make", f"-j{jobs}", target], src_dir)


def clean_for_cmake(lammps_dir: Path) -> None:
    src_dir = lammps_dir / "src"
    run(["make", "no-all", "purge"], src_dir)


def build_cmake(
    lammps_dir: Path,
    dftbplus_prefix: Path | None,
    build_dir: Path,
    jobs: int,
    cmake_args: list[str],
) -> None:
    cmd = ["cmake", "-S", str(lammps_dir / "cmake"), "-B", str(build_dir), "-D", "PKG_DFTBP=ON"]
    if dftbplus_prefix is not None:
        cmd.extend(["-D", f"DFTBPLUS_PREFIX={dftbplus_prefix}"])
    cmd.extend(cmake_args)
    run(cmd, lammps_dir)
    run(["cmake", "--build", str(build_dir), "--", f"-j{jobs}"], lammps_dir)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Stage the DFTBP package into a LAMMPS source tree and optionally build it."
    )
    parser.add_argument("--lammps-dir", required=True, help="Path to the LAMMPS source tree")
    parser.add_argument(
        "--dftbplus-prefix",
        help="Path to a DFTB+ installation prefix containing lib/ and include/",
    )
    parser.add_argument(
        "--build-system",
        choices=("stage", "make", "cmake"),
        default="stage",
        help="Whether to only stage files or also run a specific build flow",
    )
    parser.add_argument("--build", action="store_true", help="Run the selected build flow after staging")
    parser.add_argument("--make-target", default="mpi", help="LAMMPS make target to build")
    parser.add_argument("--build-dir", help="Out-of-source CMake build directory")
    parser.add_argument("--jobs", "-j", type=int, default=4, help="Parallel build jobs")
    parser.add_argument(
        "--cmake-arg",
        action="append",
        default=[],
        help="Extra argument to forward to CMake configure",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    lammps_dir = Path(args.lammps_dir).resolve()
    dftbplus_prefix = Path(args.dftbplus_prefix).resolve() if args.dftbplus_prefix else None

    if not lammps_dir.exists():
        raise SystemExit(f"LAMMPS directory does not exist: {lammps_dir}")

    stage_into_lammps(lammps_dir, dftbplus_prefix)
    print(f"Staged DFTBP into {lammps_dir}")

    if not args.build:
        return 0

    if args.build_system == "stage":
        raise SystemExit("--build requires --build-system make or cmake")

    if args.build_system == "make":
        build_make(lammps_dir, args.jobs, args.make_target)
    else:
        clean_for_cmake(lammps_dir)
        build_dir = Path(args.build_dir).resolve() if args.build_dir else (lammps_dir / "_build_dftbp")
        build_cmake(lammps_dir, dftbplus_prefix, build_dir, args.jobs, args.cmake_arg)

    return 0


if __name__ == "__main__":
    sys.exit(main())
